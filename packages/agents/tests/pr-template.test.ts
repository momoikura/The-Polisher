import { describe, it, expect } from "vitest";
import { aiCheckboxes, findPrTemplate, loadPrTemplate, templateHeadings } from "../src/maintainer/pr-template.js";
import { prChecks } from "../src/maintainer/checks.js";
import { buildLaneRepairMessages } from "../src/maintainer/prompts.js";
import { DEMO_SNAPSHOT } from "../src/maintainer/simulated.js";
import type { Validation } from "../src/maintainer/sandbox.js";

// Rich's template, shortened: instructions in comments, fixed headings, an AI checkbox, a placeholder.
const TEMPLATE = `<!--
Bugfixes are always welcome of course.
## Not a heading
-->

## Type of changes

- [ ] Bug fix
- [ ] Tests

## AI?

- [ ] AI was used to generate this PR

## Checklist

- [ ] I accept that @maintainer may be pedantic in the code review.

## Description

Please describe your changes here.`;

const SRC = "tinyslug/__init__.py";
const snapshot = { ...DEMO_SNAPSHOT, prTemplate: TEMPLATE };
const bundle = { code: { [SRC]: DEMO_SNAPSHOT.files[SRC] + "\n# changed\n" }, docs: {}, pr: "" };
const proven = {
  install: { ok: true, logTail: "" },
  compile: { ok: true, errors: [] },
  lint: { issues: [] },
  tests: { ran: true, total: 5, passed: 5, failed: 0, errors: 0, skipped: 0, failures: [], outputTail: "" },
  failToPass: { ran: true, newTests: ["t"], failedOnBase: true, passedAfter: true },
  durationMs: 1,
} as Validation;

const FILLED = `# Drop punctuation in slugify

## Type of changes

- [x] Bug fix
- [x] Tests

## AI?

- [x] AI was used to generate this PR

## Checklist

- [ ] I accept that @maintainer may be pedantic in the code review.

## Description

Fixes #7. ${SRC} now builds the slug from alphanumeric words.

Generated by ThePolisher (AI agent).`;

const check = (pr: string, type: string, snap = snapshot) => prChecks(pr, bundle, snap, proven).find((c) => c.testType === type)!;

describe("findPrTemplate", () => {
  it("finds the template where GitHub looks, preferring .github/", () => {
    expect(findPrTemplate(["README.md", "docs/pull_request_template.md", ".github/PULL_REQUEST_TEMPLATE.md"])).toBe(".github/PULL_REQUEST_TEMPLATE.md");
    expect(findPrTemplate(["pull_request_template.md", "docs/pull_request_template.md"])).toBe("pull_request_template.md");
  });

  it("finds none in a repo without one, and skips the multiple-template folder", () => {
    expect(findPrTemplate(["README.md", ".github/PULL_REQUEST_TEMPLATE/bug.md"])).toBeNull();
  });
});

describe("loadPrTemplate", () => {
  it("loads the template at the run's commit", async () => {
    const asked: string[] = [];
    const github = { getFile: async (_o: string, _r: string, path: string, sha: string) => (asked.push(`${path}@${sha}`), TEMPLATE) };

    expect(await loadPrTemplate(github, "o", "r", "abc", [".github/pull_request_template.md"])).toBe(TEMPLATE);
    expect(asked).toEqual([".github/pull_request_template.md@abc"]);
  });

  it("falls back to the default sections when the template can't be read", async () => {
    const github = { getFile: async () => Promise.reject(new Error("404")) };

    expect(await loadPrTemplate(github, "o", "r", "abc", [".github/pull_request_template.md"])).toBeUndefined();
  });
});

describe("template outline", () => {
  it("reads the headings, ignoring anything inside comments", () => {
    expect(templateHeadings(TEMPLATE)).toEqual(["Type of changes", "AI?", "Checklist", "Description"]);
  });

  it("finds the checkbox that asks whether AI was used", () => {
    expect(aiCheckboxes(TEMPLATE)).toEqual(["AI was used to generate this PR"]);
  });
});

describe("PR checks with a template", () => {
  it("passes a PR that fills the template in", () => {
    expect(check(FILLED, "pr_template").passed).toBe(true);
    expect(check(FILLED, "pr_structure").passed).toBe(true);
  });

  it("wants every heading of the template, in place of its own sections", () => {
    const result = check(FILLED.replace("## Checklist", "## Notes"), "pr_template");

    expect(result.passed).toBe(false);
    expect(result.message).toContain('"Checklist"');
  });

  it("wants the author instructions in comments removed", () => {
    expect(check(`${FILLED}\n<!-- Please describe your changes here. -->`, "pr_template").passed).toBe(false);
  });

  it("wants the AI checkbox ticked, since ThePolisher wrote the PR", () => {
    const result = check(FILLED.replace("- [x] AI was used", "- [ ] AI was used"), "pr_template");

    expect(result.passed).toBe(false);
    expect(result.message).toContain("AI was used to generate this PR");
  });

  it("wants the template's placeholder text replaced", () => {
    expect(check(`${FILLED}\nPlease describe your changes here.`, "pr_template").passed).toBe(false);
  });

  it("has no template check for a repo without a template", () => {
    expect(prChecks(FILLED, bundle, DEMO_SNAPSHOT, proven).some((c) => c.testType === "pr_template")).toBe(false);
  });
});

describe("AI disclosure", () => {
  it("wants every PR to say ThePolisher wrote it", () => {
    expect(check(FILLED, "pr_ai_disclosed").passed).toBe(true);
    expect(check(FILLED.replace("Generated by ThePolisher (AI agent).", ""), "pr_ai_disclosed").passed).toBe(false);
  });
});

describe("WritePolish prompt", () => {
  it("asks for the template to be filled in, and shows it as data", () => {
    const [system, user] = buildLaneRepairMessages("write", snapshot, { ...bundle, pr: FILLED }, proven, [], [], "");

    expect(system.content).toContain("pull request template");
    expect(system.content).not.toContain('Then "## Summary"');
    expect(user.content).toContain("I accept that @maintainer may be pedantic");
  });

  it("keeps the default sections for a repo without a template", () => {
    const [system] = buildLaneRepairMessages("write", DEMO_SNAPSHOT, { ...bundle, pr: FILLED }, proven, [], [], "");

    expect(system.content).toContain('Then "## Summary"');
  });
});
